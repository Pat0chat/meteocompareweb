import assert from 'node:assert/strict';
import fs from 'node:fs';
const app=fs.readFileSync(new URL('../../../js/app.js',import.meta.url),'utf8');
const css=fs.readFileSync(new URL('../../../styles.css',import.meta.url),'utf8');
const icons=fs.readFileSync(new URL('../../../js/ui/weather-icons.js',import.meta.url),'utf8');
const summary=app.slice(app.indexOf('function renderTodaySummary('),app.indexOf('function scenarioLabel('));
const uvCard=app.slice(app.indexOf('function renderTodayUvCard('),app.indexOf('function renderCityCard('));
assert.match(summary,/renderTodayUvCard\(uvMaxForDate\(f,agg\.date\)\)/,'UV must be sixth summary tile');
assert.doesNotMatch(summary,/\$\{renderUvGauge\(uvMaxForDate\(f,agg\.date\)\)\}/,'UV must no longer float above the summary grid');
assert.match(uvCard,/class="summary-dispersion summary-uv-card metric-uv/,'UV should use regular summary card boundaries');
assert.match(uvCard,/class="summary-dispersion-head"/,'UV should share tile header layout');
assert.match(uvCard,/class="summary-dispersion-value"/,'UV should share the numeric typography');
assert.match(uvCard,/renderUvGauge\(value,\{summary:true\}\)/,'UV must retain a gauge in its tile');
assert.match(uvCard,/singleSourceEstimate/,'UV must indicate that this is not a model consensus');
assert.doesNotMatch(uvCard,/modelConvergence|summary-agreement/,'UV tile must not invent a multi-model convergence');
assert.match(app,/renderUvGauge\(uvMaxForDate\(f,today\)\)/,'home card keeps existing full gauge');
assert.match(app,/summary\?'':`<div class="uv-gauge-header"/,'embedded gauge should avoid duplicate heading/value');
assert.match(css,/\.summary-uv-card \.uv-gauge-embedded \{/,'embedded gauge must have no stand-alone border');
assert.match(css,/\.summary-dispersion\.metric-uv \{/,'UV colors must inherit risk scale');
assert.match(icons,/uv:'<g class="wx-metric-stroke"/,'UV icon should be rendered by the shared weather icon system');
console.log('Today UV tile grid layout: OK');
