import fs from 'node:fs';
import assert from 'node:assert/strict';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const version=read('VERSION').trim(),app=read('js/app.js'),css=read('styles.css'),sw=read('sw.js');
assert.equal(version,'1.10.17');
assert.match(sw,/APP_VERSION = '1\.10\.17'/);
assert.match(sw,/CACHE_VERSION = 'v49-home-polish'/);
const home=app.slice(app.indexOf('function homeConsensusWeights'),app.indexOf('function renderCityDetail'));
assert.match(home,/class="home-hero"/);
assert.match(home,/homeModernKicker/);
assert.match(home,/home-search-trigger/);
assert.doesNotMatch(home,/home-hero-mark/);
assert.doesNotMatch(home,/home-city-shortcut/);
assert.doesNotMatch(home,/homeModernLead/);
assert.match(home,/--heat-hue:/);
assert.match(home,/home-mini-hour .*style="--heat-hue:/);
assert.match(home,/precipitationConditionalMm/);
assert.match(home,/tempMinMax/);
const card=home.slice(home.indexOf('function renderCityCard'),home.indexOf('function renderHeatmap'));
assert.match(card,/home-weather-facts/);
assert.doesNotMatch(card,/home-weather-range/);
assert.doesNotMatch(card,/homeModelSignal/);
assert.match(css,/\.home-mini-timeline\s*\{[^}]*gap:1px[^}]*border-radius:var\(--radius-md\)/s);
assert.match(css,/\.home-mini-hour\s*\{[^}]*background:hsl\(var\(--heat-hue\)/s);
assert.match(css,/\.home-hero-copy\s*\{[^}]*grid-template-columns:/s);
console.log('MeteoCompare Web 1.10.17 home polish: OK');
