import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=p=>fs.readFileSync(p,'utf8');
const worker=read('worker.js'),wrangler=read('wrangler.jsonc'),app=read('js/app.js'),css=read('styles.css'),sw=read('sw.js'),admin=read('admin.html'),adminCss=read('admin.css'),adminJs=read('admin.js'),network=read('js/network-config.js');
for(const path of ['/_mcx/messages','/_mcx/admin/messages'])assert.ok(worker.includes(path)||network.includes(path),`missing messages endpoint ${path}`);
assert.match(worker,/UserMessageStore/);
assert.match(wrangler,/"name": "USER_MESSAGES"/);
assert.match(wrangler,/"class_name": "UserMessageStore"/);
assert.match(wrangler,/"tag": "user-messages-v1"/);
assert.match(app,/renderUserMessages/);
assert.match(app,/visibleUserMessages/);
assert.match(app,/dismiss-user-message/);
assert.match(app,/renderHomeVigilance\(\)\}\$\{renderUserMessages\(\)\}\$\{hasCities\?`<div class=\"home-dashboard/,'home messages must render before the saved-cities dashboard');
assert.match(app,/const globalMessages=state\.route\.name==='home'\?'':renderUserMessages\(\{compact:graphicView\}\)/,'home must not duplicate the global footer message area');
assert.match(app,/compact:graphicView/,'graphic full-screen view must use compact priority message rendering');
assert.match(css,/\.user-messages-region/);
assert.match(css,/\.home-page > \.user-messages-shell \{[^}]*width:100%[^}]*padding:0/,'embedded home messages must align with the home content without nested page padding');
assert.match(css,/var\(--semantic-info\)/);
assert.match(css,/body\.graphic-view-open \.user-messages-shell\.is-compact[^}]*bottom:/,'graphic messages must anchor to the bottom instead of the top');
assert.doesNotMatch(css,/body\.graphic-view-open \.user-messages-shell\.is-compact[^}]*top:/,'graphic messages must not use the former top offset');
assert.match(sw,/\.\/js\/user-messages\.js/,'PWA shell must contain user-message runtime');
assert.match(admin,/id="messages-management"/);
assert.match(admin,/id="user-message-form"/);
assert.match(adminJs,/saveMessage/);
assert.match(adminJs,/reloadMessages/);
assert.match(adminCss,/\.message-options label\{[^}]*white-space:nowrap/,'admin option labels must stay on one line');
assert.match(adminCss,/\.message-options input\{[^}]*width:auto/,'message option checkboxes must not inherit full-width form input sizing');
for(const lang of ['fr','en','es','de','it']){const locale=read(`js/locales/${lang}.js`);assert.match(locale,/userMessagesTitle/);assert.match(locale,/userMessageDismiss/);}
console.log('user messages web/PWA/admin integration contract: OK');
